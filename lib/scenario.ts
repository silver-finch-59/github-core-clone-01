export interface ScenarioUser {
  id: number;
  login: string;
  name: string;
  email: string;
}

export function generateUsers(rng: Rng, count: number): ScenarioUser[] {
  const used = new Set<string>();
  const users: ScenarioUser[] = [];
  for (let i = 0; i < Math.max(0, Math.trunc(count)); i += 1) {
    const first = rng.pick(FIRST_NAMES);
    const last = rng.pick(LAST_NAMES);
    const base = `${first}${last}`.replace(/[^a-z0-9-]/g, '');
    let login = base;
    let suffix = 2;
    while (used.has(login)) {
      login = `${base}-${suffix}`;
      suffix += 1;
    }
    used.add(login);
    users.push({ id: 1000 + i, login, name: `${first} ${last}`, email: `${login}@example.invalid` });
  }
  return users;
}

export interface ScenarioIdentities {
  viewer: ScenarioUser;
  teammate: ScenarioUser;
  stranger: ScenarioUser;
  users: ScenarioUser[];
  org: string;
}

let cached: ScenarioIdentities | null = null;

/** The scenario's identities, built once from the seed and frozen. */
export function scenarioIdentities(): ScenarioIdentities {
  if (cached !== null) return cached;
  const users = generateUsers(new Rng(scenarioSeedFor('users')), 12);
  const viewer = users[0] as ScenarioUser;
  const teammate = users[1] as ScenarioUser;
  const stranger = users[2] as ScenarioUser;
  const orgRng = new Rng(scenarioSeedFor('org'));
  const org = `${orgRng.pick(REPO_ADJECTIVES)}-${orgRng.pick(REPO_NOUNS)}-org`;
  cached = Object.freeze({ viewer, teammate, stranger, users, org });
  return cached;
}
