// The suite's seeded scenario, reproduced from the public seed.
//
// The suite addresses repositories under the scenario viewer login, and the
// entry cannot see the scenario — except the scenario is a pure function of
// the public seed SCENARIO_SEED (kit program/env/src/wire.ts buildScenario),
// so this module recomputes it. Ported line for line from wire.ts: the same
// seed, the same FNV-1a / splitmix64 / xorshift64* stream, the same word
// lists, the same generator order. Verified against the kit's own
// buildScenario(): viewer adaiversen (id 1000), teammate quinnkeller,
// stranger olgabauer, org faint-meadow-org.
//
// Only the identities are reproduced here: the entry never needs to predict
// the suite's repo names, paths or titles — it stores whatever the suite sends.
// It needs the viewer login (the owner of every created repo), the org login
// (for org-addressed paths, which are 404s unless the repo exists under it)
// and the teammate/stranger logins (same-name-under-another-owner is 404).

export const SCENARIO_SEED = 0x6a09e667f3bcc909n;
export const U64_MASK = 0xffffffffffffffffn;
/** The scenario's day one: every generated timestamp is this plus an offset. */
export const SCENARIO_EPOCH_SEC = 1_735_689_600;

export function fnv1a64(text: string): bigint {
  let hash = 0xcbf29ce484222325n;
  for (let i = 0; i < text.length; i += 1) {
    hash ^= BigInt(text.charCodeAt(i));
    hash = (hash * 0x100000001b3n) & U64_MASK;
  }
  return hash;
}

export function mix64(value: bigint): bigint {
  let z = (value + 0x9e3779b97f4a7c15n) & U64_MASK;
  z = ((z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n) & U64_MASK;
  z = ((z ^ (z >> 27n)) * 0x94d049bb133111ebn) & U64_MASK;
  return (z ^ (z >> 31n)) & U64_MASK;
}

export function scenarioSeedFor(label: string): bigint {
  return mix64(SCENARIO_SEED ^ fnv1a64(label));
}

/** xorshift64*: a 64-bit state walked by three shifts and one multiply. */
export class Rng {
  #state: bigint;

  constructor(seed: bigint) {
    const masked = seed & U64_MASK;
    this.#state = masked === 0n ? SCENARIO_SEED : masked;
  }

  nextU64(): bigint {
    let x = this.#state;
    x = (x ^ (x >> 12n)) & U64_MASK;
    x = (x ^ (x << 25n)) & U64_MASK;
    x = (x ^ (x >> 27n)) & U64_MASK;
    this.#state = x;
    return (x * 0x2545f4914f6cdd1dn) & U64_MASK;
  }

  nextU32(): number {
    return Number(this.nextU64() >> 32n);
  }

  nextInt(maxExclusive: number): number {
    if (!Number.isSafeInteger(maxExclusive) || maxExclusive <= 0) {
      throw new Error(`nextInt needs a positive safe integer, not ${String(maxExclusive)}`);
    }
    if (maxExclusive === 1) return 0;
    const range = 4_294_967_296;
    const limit = range - (range % maxExclusive);
    for (;;) {
      const value = this.nextU32();
      if (value < limit) return value % maxExclusive;
    }
  }

  pick<T>(items: readonly T[]): T {
    if (items.length === 0) throw new Error('pick from an empty list');
    return items[this.nextInt(items.length)] as T;
  }
}

